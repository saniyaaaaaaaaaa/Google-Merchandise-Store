/**
 * Smart Rotation Helper
 * Given a set of already displayed product IDs, returns up to `limit` products that haven't been shown yet.
 */
export function getNonRepeatingProducts(
  catalog: Product[],
  displayedIds: Set<string>,
  filterFn?: (p: Product) => boolean,
  limit: number = 4
): Product[] {
  const result: Product[] = [];
  for (const product of catalog) {
    if (result.length >= limit) break;
    if (displayedIds.has(product.id)) continue;
    if (filterFn && !filterFn(product)) continue;
    result.push(product);
  }
  // If strict filtering yields fewer than required, top up with catalog items not already in result
  if (result.length < limit) {
    for (const product of catalog) {
      if (result.length >= limit) break;
      if (result.some(p => p.id === product.id)) continue;
      if (filterFn && !filterFn(product)) continue;
      result.push(product);
    }
  }
  return result;
}
